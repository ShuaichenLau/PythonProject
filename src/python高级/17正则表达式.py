import re

text = "张三的电话是: 138-1234-5678，李四的电话是: 139-8765-4321，邮箱: test@gmail.com"

# ==========================================
# 1. re.search()：扫描整个字符串，只找【第一个】匹配项
# ==========================================
print("--- 1. re.search ---")
match = re.search(r"\d{3}-\d{4}-\d{4}", text)
if match:
    print(f"找到第一个手机号: {match.group()}")  # .group() 获取匹配到的文本
    print(f"位置索引区间: {match.span()}")       # 返回 (开始, 结束) 下标


# ==========================================
# 2. re.findall()：找出【所有】匹配项，返回一个普通列表
# ==========================================
print("\n--- 2. re.findall ---")
all_phones = re.findall(r"\d{3}-\d{4}-\d{4}", text)
print(f"找到的所有手机号: {all_phones}")
# 输出: ['138-1234-5678', '139-8765-4321']


# ==========================================
# 3. 分组捕获 ()：用括号提取核心信息
# ==========================================
print("\n--- 3. 分组捕获 () ---")
# 假设我们要分别提取区号、中间四位、后四位
match_group = re.search(r"(\d{3})-(\d{4})-(\d{4})", text)
if match_group:
    print(f"完整内容: {match_group.group(0)}")  # 0 永远代表整个匹配内容
    print(f"前三位: {match_group.group(1)}")    # 对应第 1 个括号
    print(f"中间位: {match_group.group(2)}")    # 对应第 2 个括号
    print(f"所有分组元组: {match_group.groups()}")


# ==========================================
# 4. re.sub()：正则替换（数据脱敏清洗非常常用）
# ==========================================
print("\n--- 4. re.sub ---")
# 把手机号中间四位打码为 ****
# \1 和 \3 分别引用第 1 和第 3 个括号捕获的内容
masked_text = re.sub(r"(\d{3})-\d{4}-(\d{4})", r"\1-****-\2", text)
print(f"脱敏后的文本:\n{masked_text}")


# ==========================================
# 5. re.split()：用正则规则分割字符串
# ==========================================
print("\n--- 5. re.split ---")
raw_data = "苹果; 香蕉, 橙子  西瓜\t草莓"
# 按照 分号、逗号、或者一个及以上的空格/制表符 切割
fruits = re.split(r"[;,\s]+", raw_data)
print(f"切割结果: {fruits}")
# 输出: ['苹果', '香蕉', '橙子', '西瓜', '草莓']